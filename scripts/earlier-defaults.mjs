// Writes src/core/earlier-defaults.ts: the fingerprint of every earlier version of each
// built-in rule, read from the git history of src/core/rules.ts and default-rules.ts.
// A rules file still holding one of them was never edited, so the Rules page offers the
// current version in its place. Run it after changing a built-in rule and committing:
//   node scripts/earlier-defaults.mjs
import { execFileSync } from 'node:child_process'
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import path from 'node:path'
import { pathToFileURL } from 'node:url'
import { defaultRules, normalizeRules } from '../src/core/rules.ts'
import { fingerprint } from '../src/core/rules-merge.ts'

const FILES = ['src/core/rules.ts', 'src/core/default-rules.ts']
const git = (...args) => execFileSync('git', args, { encoding: 'utf8' })

const current = new Map(normalizeRules(defaultRules()).rules.map((r) => [r.id, fingerprint(r)]))
/** id -> fingerprints of earlier versions */
const earlier = new Map()

const commits = git('log', '--format=%H', '--', ...FILES)
  .trim()
  .split('\n')
  .filter(Boolean)
for (const commit of commits) {
  const dir = mkdtempSync(path.join(tmpdir(), 'mockolla-defaults-'))
  try {
    // The whole src tree of that commit: rules.ts imports its neighbours.
    for (const file of git('ls-tree', '-r', '--name-only', commit, 'src/core', 'src/shared')
      .trim()
      .split('\n')) {
      mkdirSync(path.join(dir, path.dirname(file)), { recursive: true })
      writeFileSync(path.join(dir, file), git('show', `${commit}:${file}`))
    }
    const mod = await import(pathToFileURL(path.join(dir, 'src/core/rules.ts')).href)
    for (const rule of normalizeRules(mod.defaultRules()).rules) {
      const fp = fingerprint(rule)
      if (fp === current.get(rule.id)) continue
      if (!earlier.has(rule.id)) earlier.set(rule.id, new Set())
      earlier.get(rule.id).add(fp)
    }
  } catch (e) {
    console.warn(`skipped ${commit.slice(0, 7)}: ${e instanceof Error ? e.message : e}`)
  } finally {
    rmSync(dir, { recursive: true, force: true })
  }
}

const body = [...earlier.keys()]
  .sort()
  .map((id) => `  '${id}': [${[...earlier.get(id)].map((f) => `'${f}'`).join(', ')}],`)
  .join('\n')
writeFileSync(
  'src/core/earlier-defaults.ts',
  `/**
 * Fingerprints (rules-merge.ts) of earlier versions of the built-in rules, by id.
 * Generated by scripts/earlier-defaults.mjs from the git history - do not edit by hand.
 */
export const EARLIER_DEFAULTS: Readonly<Record<string, readonly string[]>> = {
${body}
}
`,
)
console.log(`${earlier.size} built-in rules have earlier versions`)
